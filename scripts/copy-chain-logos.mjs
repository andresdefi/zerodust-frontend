// Chains whose logo lives in the token set (the chain shares its token's mark)
const TOKENS = { 747: 'FLOW' };

const root = new URL('../node_modules/@web3icons/core/dist/svgs/', import.meta.url);
const out = new URL('../public/chains/', import.meta.url);
mkdirSync(out, { recursive: true });

let copied = 0;
for (const [kind, map] of [['networks', NETWORKS], ['tokens', TOKENS]]) {
  for (const [chainId, slug] of Object.entries(map)) {
    const { default: svg } = await import(new URL(`${kind}/background/${slug}.svg.js`, root).href);
    writeFileSync(new URL(`${chainId}.svg`, out), svg.trim() + '\n');
    copied += 1;
  }
}
const ids = [...Object.keys(NETWORKS), ...Object.keys(TOKENS)].map(Number).sort((a, b) => a - b);
writeFileSync(
  new URL('../src/chains/logo-ids.ts', import.meta.url),
  `// Generated by scripts/copy-chain-logos.mjs: chains with a logo in public/chains/\nexport const LOGO_IDS: ReadonlySet<number> = new Set([\n  ${ids.join(', ')},\n]);\n`
);
console.log(`copied ${copied} logos to public/chains/`);
